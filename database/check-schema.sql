SELECT 'missing table' AS problem, e.table_name, '' AS column_name
  FROM smartdtr_expected e
 WHERE NOT EXISTS (SELECT 1 FROM information_schema.TABLES t
                    WHERE t.TABLE_SCHEMA = DATABASE() AND t.TABLE_NAME = e.table_name)
 GROUP BY e.table_name
UNION ALL
SELECT 'missing column', e.table_name, e.column_name
  FROM smartdtr_expected e
 WHERE EXISTS (SELECT 1 FROM information_schema.TABLES t
                WHERE t.TABLE_SCHEMA = DATABASE() AND t.TABLE_NAME = e.table_name)
   AND NOT EXISTS (SELECT 1 FROM information_schema.COLUMNS c
                    WHERE c.TABLE_SCHEMA = DATABASE() AND c.TABLE_NAME = e.table_name
                      AND c.COLUMN_NAME = e.column_name)
UNION ALL
SELECT 'no auto_increment', c.TABLE_NAME, c.COLUMN_NAME
  FROM information_schema.COLUMNS c
 WHERE c.TABLE_SCHEMA = DATABASE()
   AND c.COLUMN_NAME = 'id'
   AND c.DATA_TYPE IN ('tinyint', 'smallint', 'mediumint', 'int', 'bigint')
   AND c.EXTRA NOT LIKE '%auto_increment%'
ORDER BY 1, 2, 3;

DROP TEMPORARY TABLE smartdtr_expected;
